// Builds css/canonical-shelf.css from css/src. Lengths are written in board units: 12u becomes calc(12 * var(--u)).
// Run: bun docs/design/templates/build.mjs  (or node)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const parts = ['tokens.css', 'shell.css', 'screens.css'].map(name => readFileSync(join(here, 'css/src', name), 'utf8'));
const units = /(^|[^\w.#-])(-?\d*\.?\d+)u(?![\w-])/g;
const css = parts.join('\n')
  .replace("@import url('../fonts/fonts.css');", '')
  .replace(units, (_, lead, n) => `${lead}calc(${n} * var(--u))`);
writeFileSync(join(here, 'css/canonical-shelf.css'),
  `/* Generated by build.mjs from css/src. Do not edit by hand. */\n@import url('../fonts/fonts.css');\n${css}`);
console.log('built css/canonical-shelf.css');
