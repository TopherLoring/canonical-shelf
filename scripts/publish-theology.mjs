import {readFile,writeFile} from 'node:fs/promises';

const copies=[
  ['content/statement/statement-of-faith-compact.md','public/data/statement-of-faith.md'],
  ['content/theology/policy.json','public/data/theology-policy.json'],
  ['content/theology/sources.json','public/data/theology-sources.json']
];

for(const [source,target] of copies){
  const content=await readFile(source,'utf8');
  await writeFile(target,content.endsWith('\n')?content:`${content}\n`,'utf8');
}

// The internal belief context is never published as a site file (crawlers and AI tools could read it).
// It is compiled into the Theologian's server code, which visitors cannot download.
import {mkdir,rm} from 'node:fs/promises';
await mkdir('worker/generated',{recursive:true});
await writeFile('worker/generated/belief-context.ts',`// GENERATED by scripts/publish-theology.mjs from content/statement/statement-of-faith-v3.md. Server-only.\nexport const BELIEF_CONTEXT = ${JSON.stringify(await readFile('content/statement/statement-of-faith-v3.md','utf8'))};\n`,'utf8');
await rm('public/data/theologian-belief-context.md',{force:true});
console.log('published compact Statement of Faith, theology policy, and vetted source catalog; compiled the internal belief context into the Theologian server (not public)');
