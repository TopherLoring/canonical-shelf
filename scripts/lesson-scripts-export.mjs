// Writes docs/v7/LESSON_SCRIPTS.md: every lesson compiled into a single script, in Learning Path order, for the
// content revision (content.lesson-shape.v1-2026-10-05). Each lesson reads top to bottom like a lecture: its title,
// its one objective, its reading, then its points (the authored sections) with the details beneath each, then its
// glossary. Checks, readings and reflections stay in place as bracketed markers. No division into steps.
// Run: bun scripts/lesson-scripts-export.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { parseLesson } from './lib/lesson-parse.mjs';
import { unitById } from '../content/curriculum/structure.mjs';

const outline = JSON.parse(readFileSync('content/pathway/outline.json', 'utf8'));
const order = new Map(), where = new Map();
for (const mod of outline.modules || []) for (const unit of mod.units || []) for (const l of unit.lessons || []) {
  order.set(l.id, order.size);
  where.set(l.id, { module: mod.title || mod.id, unit: unitById[unit.unitId]?.title || unit.unitId });
}
const lessons = readdirSync('content/pathway/lessons').filter(f => f.endsWith('.md'))
  .map(f => parseLesson(readFileSync(`content/pathway/lessons/${f}`, 'utf8'), f))
  .sort((a, b) => (order.get(a.meta.id) ?? 1e9) - (order.get(b.meta.id) ?? 1e9));

const out = ['# Lesson scripts', '',
  'Generated by `bun scripts/lesson-scripts-export.mjs` from `content/pathway/lessons/`. Each lesson as one script: one objective, its points (the authored sections), and the details beneath each point. This is the working text for the content revision (voice: `content.voice.v1-2026-10-05`).', ''];
let lastModule, lastUnit, words = 0;
for (const l of lessons) {
  const w = where.get(l.meta.id) || {};
  if (w.module !== lastModule) { out.push(`## ${w.module || 'Not in the outline'}`, ''); lastModule = w.module; lastUnit = null; }
  if (w.unit !== lastUnit) { out.push(`### ${w.unit || ''}`, ''); lastUnit = w.unit; }
  out.push(`#### ${l.meta.title}`, '', `*\`${l.meta.id}\`* · **Objective:** ${l.meta.objective} · **Reading:** ${l.meta.reading || '—'}`, '');
  for (const [i, s] of l.sections.entries()) {
    out.push(`**${i + 1}. ${s.title}**`, '');
    for (const b of s.blocks) {
      if (b.type === 'prose') { out.push(b.text, ''); words += b.text.split(/\s+/).length; }
      else if (b.type === 'callout') { out.push(`> ${b.text}`, ''); words += b.text.split(/\s+/).length; }
      else if (b.type === 'reading') out.push(`[Reading: ${l.meta.reading}]`, '');
      else if (b.type === 'check') { const c = l.checks[b.index] || {}; out.push(`[Check: ${c.title || ''}] ${c.prompt || ''}`, ''); }
      else if (b.type === 'reflect') out.push(`[Reflection] ${l.reflection?.prompt || ''}`, '');
      else if (b.type === 'visual') out.push('[Visual]', '');
    }
  }
  const g = Object.entries(l.meta.glossary || {});
  if (g.length) out.push('*Glossary:* ' + g.map(([t, d]) => `**${t}**: ${d}`).join(' · '), '');
  out.push('---', '');
}
writeFileSync('docs/v7/LESSON_SCRIPTS.md', out.join('\n') + '\n');
console.log(`lesson-scripts-export: ${lessons.length} lessons, about ${words} words of prose -> docs/v7/LESSON_SCRIPTS.md`);
