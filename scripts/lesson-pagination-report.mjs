// Step 3, node S3.E: writes docs/v7/LESSON_PAGINATION_REVIEW.md, the document Chris uses for the one-time revision
// pass (curriculum.lesson.pagination.revision-pass-2026-10-05). It lists every lesson's proposed cards from the
// build-time divider, puts the breaks most worth a look first, and shows each seam (the sentence before a break and
// the sentence after it) so the review does not mean rereading every lesson.
//
//   bun scripts/lesson-pagination-report.mjs           write the report
//   bun scripts/lesson-pagination-report.mjs --check   fail if the report is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { divideAll, geometry, loadContext, CEILINGS, TARGET } from './lesson-divider.mjs';
import { unitById } from '../content/curriculum/structure.mjs';

const OUT = 'docs/v7/LESSON_PAGINATION_REVIEW.md';
// A card that opens mid-paragraph with one of these words may lean on the sentence left on the previous card.
const LEANS_BACK = /^["“‘(]?(It|Its|This|These|That|Those|They|Their|Them|He|She|His|Her|Such|So|But|And|Or|Yet|Then|Therefore|Thus|Here|There|Both|Each|Neither|Either|Instead|Still)\b/;

const text = u => (u.kind === 'sentence' || u.kind === 'callout' ? u.text : u.kind === 'reading' ? `[reading: ${u.reference}, ${u.mode === 'inline' ? 'quoted on the card' : 'link + popover'}]` : `[${u.kind}${u.check?.title ? `: ${u.check.title}` : ''}]`);
const clip = (s, n, fromEnd = false) => (s.length <= n ? s : fromEnd ? `…${s.slice(-n).replace(/^\S*\s/, '')}` : `${s.slice(0, n).replace(/\s\S*$/, '')}…`);
const esc = s => String(s).replace(/\|/g, '\\|');

export function buildReport() {
  const { type } = loadContext();
  const geo = geometry(type);
  // Curriculum order (the outline: module, unit, lesson), so the review reads like the Learning Path.
  const outline = JSON.parse(readFileSync('content/pathway/outline.json', 'utf8'));
  const order = new Map();
  const where = new Map();
  for (const mod of outline.modules || []) for (const unit of mod.units || []) for (const l of unit.lessons || []) {
    order.set(l.id, order.size);
    where.set(l.id, { module: mod.title || mod.id, unit: unitById[unit.unitId]?.title || unit.unitId });
  }
  const lessons = divideAll().sort((a, b) => (order.get(a.lesson) ?? 1e9) - (order.get(b.lesson) ?? 1e9));
  const cards = lessons.flatMap(l => l.steps.flatMap(s => s.cards.map((c, i) => ({ lesson: l, step: s, card: c, index: i }))));
  // Seam flags computed here, from each card and the one before it in the same step.
  for (const x of cards) {
    x.notes = [...x.card.flags];
    const first = x.card.units[0];
    if (x.index > 0 && first.kind === 'sentence' && !first.paraStart && LEANS_BACK.test(first.text)) x.notes.push('leans-back');
    if (x.index > 0 && first.kind === 'sentence' && !first.paraStart) x.midParagraph = true;
  }
  const flagged = name => cards.filter(x => x.notes.includes(name));
  const sizes = cards.map(x => x.card.chars).filter(n => n > 0).sort((a, b) => a - b);
  const split = lessons.flatMap(l => l.steps).filter(s => s.cards.length > 1).length;
  const steps = lessons.flatMap(l => l.steps).length;
  const seam = x => {
    const prev = x.step.cards[x.index - 1];
    return `> ${esc(clip(text(prev.units.at(-1)), 110, true))}\n>\n> **↓ card ${x.index + 1}:** ${esc(clip(text(x.card.units[0]), 140))}`;
  };

  const out = [];
  out.push('# Lesson pagination review', '');
  out.push('Generated by `bun scripts/lesson-pagination-report.mjs` from the build-time divider (S3.D, S3.D2). Do not edit by hand; edit the lessons, then regenerate.', '');
  out.push('## How to use this', '');
  out.push('- Every step of every lesson has been divided into cards. Each card is a step the learner sees; the first card keeps the step\'s id and later cards get `-2`, `-3`.');
  out.push('- **Nothing has been reworded.** Sentences are never split, content never moves between steps, and order never changes; the divider\'s tests check this for every lesson.');
  out.push('- Review section 1 first. Most seams in section 3 are fine; skim them for anything that reads oddly.');
  out.push('- To fix a break: mark the card id and what you want (move the break, merge, or reword). Rewording is allowed only at these breaks, and only after you approve each edit (`curriculum.lesson.pagination.revision-pass-2026-10-05`).', '');
  out.push('## The numbers', '');
  out.push(`| | |`, `|---|---|`);
  out.push(`| Lessons | ${lessons.length} |`);
  out.push(`| Authored steps | ${steps} (${split} split into more than one card) |`);
  out.push(`| Cards | ${cards.length} |`);
  out.push(`| Card text, median / longest | ${sizes[sizes.length >> 1]} / ${sizes.at(-1)} characters (target about ${TARGET.min}-${TARGET.max}; ceilings ${CEILINGS[1]} / ${CEILINGS[2]} / ${CEILINGS[3]}) |`);
  out.push(`| Step body | ${geo.primary.lines} lines × about ${geo.primary.charsPerLine} characters (16px Source Sans 3, line height ${type.lineHeight}) |`);
  out.push(`| Cards that do not fit | ${flagged('overflow').length + flagged('over-ceiling').length} |`);
  out.push('');

  out.push('## 1. Worth a look', '');
  const leans = flagged('leans-back');
  const orphans = flagged('orphan');
  out.push(`### Short last cards (${orphans.length})`, '', 'Under 120 characters, left on their own because merging them would make the card before too long.', '');
  for (const x of orphans) out.push(`- \`${x.lesson.lesson}#${x.card.id}\` (${x.card.chars} chars): ${esc(clip(x.card.units.map(text).join(' '), 200))}`);
  out.push('', `### Cards that open by leaning on the previous card (${leans.length})`, '', 'The card starts mid-paragraph with a word like *It, This, They, But, So* that points back to the sentence before the break. Many read fine; some may need the break moved or a word changed.', '');
  for (const x of leans) out.push(`**\`${x.lesson.lesson}#${x.card.id}\`**`, '', seam(x), '');

  out.push(`## 2. Checks and other blocks on their own card (${flagged('block-alone').length})`, '', 'A check, reflection, reading or visual did not fit on the card with the text before it, so it opens the next card. This is usually right (the check gets the whole card); listed so you can spot one that loses its setup.', '');
  out.push('| Card | Block | Text it follows |', '|---|---|---|');
  for (const x of flagged('block-alone')) out.push(`| \`${x.lesson.lesson}#${x.card.id}\` | ${esc(text(x.card.units[0]))} | ${esc(clip(text(x.step.cards[x.index - 1].units.at(-1)), 90, true))} |`);
  out.push('');

  out.push('## 3. Every lesson, in Learning Path order', '');
  let lastModule = null, lastUnit = null;
  for (const l of lessons) {
    const w = where.get(l.lesson) || {};
    if (w.module !== lastModule) { out.push(`## ${esc(w.module || 'Not in the outline')}`, ''); lastModule = w.module; lastUnit = null; }
    if (w.unit !== lastUnit) { out.push(`*${esc(w.unit || '')}*`, ''); lastUnit = w.unit; }
    const n = l.steps.reduce((k, s) => k + s.cards.length, 0);
    out.push(`### ${esc(l.title)} (\`${l.lesson}\`) — ${l.steps.length} steps → ${n} cards`, '');
    for (const s of l.steps) {
      out.push(`- **${esc(s.title)}** \`#${s.id}\`: ${s.cards.map(c => `${c.chars} chars${c.flags.length ? ` (${c.flags.join(', ')})` : ''}`).join(' · ')}`);
      s.cards.forEach((c, i) => {
        if (i === 0) return;
        const x = cards.find(y => y.card === c);
        out.push(`  - break before \`${c.id}\`${x.midParagraph ? ' (mid-paragraph)' : ''}: ${esc(clip(text(s.cards[i - 1].units.at(-1)), 80, true))} **↓** ${esc(clip(text(c.units[0]), 90))}`);
      });
    }
    out.push('');
  }
  return out.join('\n') + '\n';
}

const report = buildReport();
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== report) { console.error(`lesson-pagination-report: ${OUT} is stale. Run: bun scripts/lesson-pagination-report.mjs`); process.exit(1); }
  console.log('lesson-pagination-report: ok');
} else {
  writeFileSync(OUT, report);
  const lines = report.split('\n');
  console.log(`lesson-pagination-report: wrote ${OUT} (${lines.length} lines, ${Math.round(report.length / 1024)} KB)`);
}
