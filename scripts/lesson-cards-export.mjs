// Writes two readable documents for reviewing lesson content and its division into cards:
//   docs/v7/LESSON_CONTENT.md  every lesson's steps in full, as authored (no breaks)
//   docs/v7/LESSON_CARDS.md    each section divided into steps by the break rule (ui.lesson.card.break-rule-v2-2026-10-05),
//                              each step in full with its count
// Run: bun scripts/lesson-cards-export.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { divideAll, BREAK_AT, PARAGRAPH_COST, BLOCK_COST, LINE_CHARS } from './lesson-divider.mjs';
import { parseLesson } from './lib/lesson-parse.mjs';
import { unitById } from '../content/curriculum/structure.mjs';

const outline = JSON.parse(readFileSync('content/pathway/outline.json', 'utf8'));
const order = new Map(), where = new Map();
for (const mod of outline.modules || []) for (const unit of mod.units || []) for (const l of unit.lessons || []) {
  order.set(l.id, order.size);
  where.set(l.id, { module: mod.title || mod.id, unit: unitById[unit.unitId]?.title || unit.unitId });
}
const lessons = divideAll().sort((a, b) => (order.get(a.lesson) ?? 1e9) - (order.get(b.lesson) ?? 1e9));

const block = u => {
  if (u.kind === 'callout') return `> ${u.text}`;
  if (u.kind === 'reading') return u.mode === 'inline' ? `> **${u.reference}** (Scripture, quoted on the card): ${u.text}` : `**[Scripture link → popover: ${u.reference}]**`;
  if (u.kind === 'check') return `**[Check: ${u.check?.title || ''}]** ${u.check?.prompt || ''}`;
  if (u.kind === 'reflect') return `**[Reflection]** ${u.reflect?.prompt || ''}`;
  if (u.kind === 'visual') return '**[Visual]**';
  return '';
};
// Units back into paragraphs: sentences of one paragraph join with a space; every block is its own paragraph.
function render(units) {
  const out = [];
  let para = null;
  for (const u of units) {
    if (u.kind === 'sentence') {
      if (u.paraStart || para === null) { if (para) out.push(para); para = u.text; }
      else para += ' ' + u.text;
    } else { if (para) out.push(para); para = null; out.push(block(u)); }
  }
  if (para) out.push(para);
  return out.join('\n\n');
}

const content = ['# Lesson content (as authored, before division)', '', 'Generated by `bun scripts/lesson-cards-export.mjs`. Every lesson in Learning Path order; each step in full.', ''];
const cards = ['# Lesson steps (each section divided)', '', `Generated by \`bun scripts/lesson-cards-export.mjs\`. Each authored section is divided into steps independently. Count every character on a step (spaces and punctuation included, starting again on each step); each new paragraph after the first adds ${PARAGRAPH_COST}; a block counts ${BLOCK_COST} plus ${LINE_CHARS} per ${LINE_CHARS}-character line of its text; break at the last sentence end at or before ${BREAK_AT}. Sentences and blocks are never divided.`, ''];
let lastModule, lastUnit, nCards = 0;
for (const l of lessons) {
  const w = where.get(l.lesson) || {};
  for (const doc of [content, cards]) {
    if (w.module !== lastModule) doc.push(`## ${w.module || 'Not in the outline'}`, '');
    if (w.unit !== lastUnit) doc.push(`### ${w.unit || ''}`, '');
  }
  lastModule = w.module; lastUnit = w.unit;
  const sections = [];
  for (const c of l.cards) { if (!sections.length || sections.at(-1).id !== c.section) sections.push({ id: c.section, title: c.title, cards: [] }); sections.at(-1).cards.push(c); }
  content.push(`#### ${l.title} (\`${l.lesson}\`)`, '');
  cards.push(`#### ${l.title} (\`${l.lesson}\`) — ${sections.length} sections → ${l.cards.length} steps`, '');
  let n = 0;
  sections.forEach((s, si) => {
    content.push(`**Section ${si + 1}. ${s.title}**`, '', render(s.cards.flatMap(c => c.units)), '');
    cards.push(`**Section ${si + 1}. ${s.title}**`, '');
    for (const c of s.cards) {
      n++; nCards++;
      cards.push(`*${n} of ${l.cards.length}* \`${c.id}\` — count ${c.count}${c.flags.length ? ` — ${c.flags.join(', ')}` : ''}`, '', render(c.units), '', '---', '');
    }
  });
}
writeFileSync('docs/v7/LESSON_CONTENT.md', content.join('\n') + '\n');
writeFileSync('docs/v7/LESSON_CARDS.md', cards.join('\n') + '\n');
console.log(`lesson-cards-export: ${lessons.length} lessons, ${nCards} steps -> docs/v7/LESSON_CONTENT.md, docs/v7/LESSON_CARDS.md`);
